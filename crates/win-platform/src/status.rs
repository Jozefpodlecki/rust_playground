use winapi::shared::{ntdef::NTSTATUS, ntstatus::{STATUS_ACCESS_DENIED, STATUS_INVALID_HANDLE, STATUS_NOT_FOUND}};


#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct NtStatus(i32);

impl NtStatus {
    pub const fn raw(&self) -> i32 {
        self.0
    }

    pub const fn from_raw(raw: i32) -> Self {
        Self(raw)
    }

    pub const fn is_success(&self) -> bool {
        self.0 == 0
    }

     pub const fn is_alerted(&self) -> bool {
        self.0 == STATUS_ALERTED
    }

    pub const fn is_pending(&self) -> bool {
        self.0 == STATUS_PENDING
    }

    pub const fn is_timeout(&self) -> bool {
        self.0 == STATUS_TIMEOUT
    }

    pub const fn ok(self) -> Result<(), NtError> {
        if self.is_success() || self.is_alerted() { Ok(()) } else { Err(NtError(self.0)) }
    }
}

impl core::fmt::Display for NtStatus {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "{} (0x{:08X})", NtError(self.0).name(), self.0 as u32)
    }
}

